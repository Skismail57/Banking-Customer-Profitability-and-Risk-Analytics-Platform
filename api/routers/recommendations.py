@router.get("/recommendations/segment/{segment}")
async def get_segment_recommendations(
    segment: str,
    db: Session = Depends(get_db),
    current_user = Depends(require_permission(Permission.ANALYTICS_READ))
):
    """Get recommendations for a specific segment.
    
    Args:
        segment: Segment name
        db: Database session
    
    Returns:
        Segment recommendations
    """
    try:
        # Initialize decision engine
        data_loader = DataLoader()
        decision_engine = DecisionEngine(data_loader=data_loader)
        
        # Generate segment recommendations
        segment_recommendations = decision_engine.generate_segment_recommendations()
        
        if segment not in segment_recommendations:
            raise HTTPException(status_code=404, detail=f"Segment {segment} not found")
        
        return {
            "segment": segment,
            "recommendations": [rec.to_dict() for rec in segment_recommendations[segment]]
        }
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error fetching segment recommendations: {e}")
        raise HTTPException(status_code=500, detail="Error fetching segment recommendations")
